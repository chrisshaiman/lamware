"""Persisted firewall rules must not carry podman's port-publish chains (#580).

`netfilter-persistent save` is `iptables-save` of the live tables, and those
include CNI-HOSTPORT-DNAT / CNI-DN-* (NETAVARK-* on newer podman) with a DNAT
aimed at the container IP of the moment. Restored at boot, that stale DNAT sits
ahead of the one podman creates for the new container and wins: the local model
"listening" for six days while every request timed out, and again after the
2026-10-18 reboot, when a pipeline deploy had persisted `--to-destination
10.88.0.12` and the new container came up at 10.88.0.2.

Behavioural: the helper's filter is run (bash) over a dump shaped like the
host's. Structural: every role that persists the firewall goes through the
helper and ships it, and none still calls `netfilter-persistent save`.
"""
import subprocess
from pathlib import Path

import pytest

yaml = pytest.importorskip("yaml")

ROOT = Path(__file__).resolve().parents[1]
HELPER = ROOT / "ansible" / "roles" / "networking" / "files" / "lamware-persist-firewall.sh"
ROLES = ROOT / "ansible" / "roles"

DUMP = """# Generated by iptables-save v1.8.10 (nf_tables)
*nat
:PREROUTING ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
:CNI-DN-55a38b96e17d5f53fc2a5 - [0:0]
:CNI-HOSTPORT-DNAT - [0:0]
:CNI-HOSTPORT-SETMARK - [0:0]
:NETAVARK-HOSTPORT-DNAT - [0:0]
:LIBVIRT_PRT - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j CNI-HOSTPORT-DNAT
-A PREROUTING -m addrtype --dst-type LOCAL -j NETAVARK-HOSTPORT-DNAT
-A OUTPUT -m addrtype --dst-type LOCAL -j CNI-HOSTPORT-DNAT
-A POSTROUTING -j LIBVIRT_PRT
-A CNI-DN-55a38b96e17d5f53fc2a5 -d 127.0.0.1/32 -p tcp -m tcp --dport 11435 -j DNAT --to-destination 10.88.0.12:11435
-A CNI-HOSTPORT-DNAT -p tcp -m multiport --dports 11435 -j CNI-DN-55a38b96e17d5f53fc2a5
-A LIBVIRT_PRT -s 192.168.100.0/24 ! -d 192.168.100.0/24 -j MASQUERADE
COMMIT
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:CNI-ADMIN - [0:0]
:CNI-FORWARD - [0:0]
:LAMWARE-GUEST-IN - [0:0]
-A INPUT -i virbr-det -j LAMWARE-GUEST-IN
-A FORWARD -j CNI-FORWARD
-A FORWARD -i virbr-det -j DROP
-A OUTPUT -m owner --uid-owner 997 -m comment --comment "pipeline: block all outbound" -j DROP
-A CNI-FORWARD -j CNI-ADMIN
COMMIT
"""


def _filtered(text: str) -> list[str]:
    out = subprocess.run(["bash", str(HELPER), "--filter"], input=text,
                         capture_output=True, text=True, check=True)
    return out.stdout.splitlines()


def test_container_chains_and_their_rules_are_dropped():
    lines = _filtered(DUMP)
    assert not [ln for ln in lines if "CNI-" in ln or "NETAVARK" in ln], lines
    assert "10.88.0.12" not in "\n".join(lines), "the stale DNAT survived the filter"


def test_everything_else_survives_verbatim():
    kept = _filtered(DUMP)
    expected = [ln for ln in DUMP.splitlines() if "CNI-" not in ln and "NETAVARK" not in ln]
    assert kept == expected
    text = "\n".join(kept)
    assert "pipeline: block all outbound" in text, "the pipeline egress DROP was lost"
    assert ":LAMWARE-GUEST-IN - [0:0]" in text and "-i virbr-det -j DROP" in text
    assert text.count("COMMIT") == 2 and "*nat" in text and "*filter" in text
    assert "LIBVIRT_PRT" in text, "libvirt's chains are not this fix's business"


def _tasks(role: str) -> list[dict]:
    return yaml.safe_load((ROLES / role / "tasks" / "main.yml").read_text(encoding="utf-8"))


def _commands(tasks: list[dict]) -> list[str]:
    out = []
    for t in tasks:
        for key in ("ansible.builtin.command", "command", "ansible.builtin.shell", "shell"):
            v = t.get(key)
            if isinstance(v, dict):
                v = v.get("cmd", "")
            if v:
                out.append(str(v))
    return out


@pytest.mark.parametrize("role", ["networking", "pipeline"])
def test_no_role_persists_with_netfilter_persistent_save(role):
    assert not [c for c in _commands(_tasks(role)) if "netfilter-persistent save" in c], role


@pytest.mark.parametrize("role", ["networking", "pipeline"])
def test_each_persisting_role_ships_and_calls_the_helper(role):
    tasks = _tasks(role)
    copies = [t for t in tasks
              if isinstance(t.get("ansible.builtin.copy"), dict)
              and t["ansible.builtin.copy"].get("dest") == "/usr/local/sbin/lamware-persist-firewall"]
    assert len(copies) == 1, f"{role}: the helper is not installed exactly once"
    assert copies[0]["ansible.builtin.copy"]["src"].endswith("lamware-persist-firewall.sh")
    assert copies[0]["ansible.builtin.copy"]["mode"] == "0755"
    calls = [c for c in _commands(tasks) if c.strip() == "/usr/local/sbin/lamware-persist-firewall"]
    assert len(calls) == 1, f"{role}: the helper is not what persists the rules"
    assert tasks.index(copies[0]) < next(i for i, t in enumerate(tasks)
                                          if str(t.get("ansible.builtin.command", "")).strip()
                                          == "/usr/local/sbin/lamware-persist-firewall"), \
        f"{role}: the helper is called before it is installed"


def test_the_helper_is_one_file_referenced_from_both_roles():
    """One source. The pipeline role points at the networking role's copy rather
    than keeping its own, so the two cannot drift."""
    assert HELPER.exists()
    src = next(t["ansible.builtin.copy"]["src"] for t in _tasks("pipeline")
               if isinstance(t.get("ansible.builtin.copy"), dict)
               and t["ansible.builtin.copy"].get("dest") == "/usr/local/sbin/lamware-persist-firewall")
    assert "networking/files/lamware-persist-firewall.sh" in src
